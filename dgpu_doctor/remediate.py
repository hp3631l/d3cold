UDEV_RULE_CONTENT = """# Automatically generated by dgpu-doctor

# Remove NVIDIA USB xHCI Host Controller devices, if present
ACTION=="add", SUBSYSTEM=="pci", ATTR{vendor}=="0x10de", ATTR{class}=="0x0c0330", ATTR{remove}="1"

# Remove NVIDIA USB Type-C UCSI devices, if present
ACTION=="add", SUBSYSTEM=="pci", ATTR{vendor}=="0x10de", ATTR{class}=="0x0c8000", ATTR{remove}="1"

# Remove NVIDIA Audio devices on boot so WirePlumber cannot block D3cold
ACTION=="add", SUBSYSTEM=="pci", ATTR{vendor}=="0x10de", ATTR{class}=="0x040300", ATTR{remove}="1"

# Enable runtime PM for NVIDIA VGA/3D controller devices on driver bind
ACTION=="bind", SUBSYSTEM=="pci", ATTR{vendor}=="0x10de", ATTR{class}=="0x030000", TEST=="power/control", ATTR{power/control}="auto"
ACTION=="bind", SUBSYSTEM=="pci", ATTR{vendor}=="0x10de", ATTR{class}=="0x030200", TEST=="power/control", ATTR{power/control}="auto"

# Disable runtime PM for NVIDIA VGA/3D controller devices on driver unbind
ACTION=="unbind", SUBSYSTEM=="pci", ATTR{vendor}=="0x10de", ATTR{class}=="0x030000", TEST=="power/control", ATTR{power/control}="on"
ACTION=="unbind", SUBSYSTEM=="pci", ATTR{vendor}=="0x10de", ATTR{class}=="0x030200", TEST=="power/control", ATTR{power/control}="on"
"""

MODPROBE_CONTENT = """# Automatically generated by dgpu-doctor

options nvidia-drm modeset=1
options nvidia "NVreg_DynamicPowerManagement=0x02"
options nvidia NVreg_UsePageAttributeTable=1 NVreg_InitializeSystemMemoryAllocations=0
"""

PRIME_RUN_CONTENT = """#!/usr/bin/env bash
# On-demand NVIDIA Prime Offload wrapper
# Forces games and apps to bind exclusively to the NVIDIA dGPU with full Vulkan/GLX acceleration.

export __NV_PRIME_RENDER_OFFLOAD=1
export __VK_LAYER_NV_optimus=NVIDIA_only
export __GLX_VENDOR_LIBRARY_NAME=nvidia
export DRI_PRIME=1

# Bind Vulkan exclusively to NVIDIA ICD if present
for icd in /usr/share/vulkan/icd.d/nvidia_icd.json /etc/vulkan/icd.d/nvidia_icd.json; do
    if [ -f "$icd" ]; then
        export VK_DRIVER_FILES="$icd"
        export VK_ICD_FILENAMES="$icd"
        break
    fi
done

unset __EGL_VENDOR_LIBRARY_FILENAMES
unset LIBVA_DRIVER_NAME

exec "$@"
"""


def fix_btop() -> Tuple[bool, str]:
    """Reconfigure ~/.config/btop/btop.conf to isolate monitoring to iGPU."""
    conf = Path.home() / ".config/btop/btop.conf"
    if not conf.exists():
        return False, "btop.conf does not exist (btop not installed or not run yet)."

    try:
        text = conf.read_text()
        modified = text

        # Turn off GPU in CPU box if set to Auto
        modified = re.sub(r'show_gpu_info\s*=\s*"Auto"', 'show_gpu_info = "Off"', modified)
        # Disable NVML PCIe speeds
        modified = re.sub(
            r"nvml_measure_pcie_speeds\s*=\s*true", "nvml_measure_pcie_speeds = false", modified
        )
        # Isolate shown GPUs to intel
        modified = re.sub(r'shown_gpus\s*=\s*"[^"]*"', 'shown_gpus = "intel"', modified)

        if modified != text:
            conf.write_text(modified)
            return True, "Optimized ~/.config/btop/btop.conf to monitor iGPU only."
        return True, "btop.conf is already optimized."
    except Exception as e:
        return False, f"Failed to modify btop.conf: {e}"


def fix_compositor_env() -> List[Tuple[bool, str]]:
    """Configure environment files so Wayland compositors don't leak NVIDIA EGL fds."""
    from .pci import find_igpu_drm_card, find_dgpu_drm_card

    results = []
    igpu_card = find_igpu_drm_card()
    dgpu_card = find_dgpu_drm_card()
    if dgpu_card:
        intel_val = f"AQ_DRM_DEVICES={igpu_card}:{dgpu_card}"
    else:
        intel_val = f"AQ_DRM_DEVICES={igpu_card}"

    # 1. ~/.config/environment.d/10-hyprland-gpu.conf
    env_dir = Path.home() / ".config/environment.d"
    env_file = env_dir / "10-hyprland-gpu.conf"
    try:
        env_dir.mkdir(parents=True, exist_ok=True)
        content = (
            f"{intel_val}\n"
            "__EGL_VENDOR_LIBRARY_FILENAMES=/usr/share/glvnd/egl_vendor.d/50_mesa.json\n"
            "VK_DRIVER_FILES=/usr/share/vulkan/icd.d/intel_icd.x86_64.json\n"
            "LIBVA_DRIVER_NAME=iHD\n"
        )
        env_file.write_text(content)
        results.append((True, f"Updated {env_file}"))
    except Exception as e:
        results.append((False, f"Failed to write {env_file}: {e}"))

    # 2. ~/.config/uwsm/env-hyprland
    uwsm_dir = Path.home() / ".config/uwsm"
    uwsm_file = uwsm_dir / "env-hyprland"
    try:
        uwsm_dir.mkdir(parents=True, exist_ok=True)
        lines = []
        if uwsm_file.exists():
            prefixes = ("export AQ_DRM_DEVICES", "export __EGL_VENDOR_LIBRARY_FILENAMES", "export VK_DRIVER_FILES", "export LIBVA_DRIVER_NAME")
            lines = [l for l in uwsm_file.read_text().splitlines() if not any(l.startswith(p) for p in prefixes)]
        lines.extend([
            f"export {intel_val}",
            "export __EGL_VENDOR_LIBRARY_FILENAMES=/usr/share/glvnd/egl_vendor.d/50_mesa.json",
            "export VK_DRIVER_FILES=/usr/share/vulkan/icd.d/intel_icd.x86_64.json",
            "export LIBVA_DRIVER_NAME=iHD",
        ])
        uwsm_file.write_text("\n".join(lines) + "\n")
        results.append((True, f"Updated {uwsm_file}"))
    except Exception as e:
        results.append((False, f"Failed to write {uwsm_file}: {e}"))

    return results


def install_prime_run() -> Tuple[bool, str]:
    """Install ~/.local/bin/prime-run."""
    bin_dir = Path.home() / ".local/bin"
    bin_file = bin_dir / "prime-run"
    try:
        bin_dir.mkdir(parents=True, exist_ok=True)
        bin_file.write_text(PRIME_RUN_CONTENT)
        bin_file.chmod(0o755)
        return True, f"Installed on-demand runner: {bin_file}"
    except Exception as e:
        return False, f"Failed to install prime-run: {e}"


def are_system_rules_installed() -> bool:
    """Check if /etc/udev/rules.d/80-nvidia-pm.rules and /etc/modprobe.d/nvidia.conf exist and match."""
    udev_path = Path("/etc/udev/rules.d/80-nvidia-pm.rules")
    modprobe_path = Path("/etc/modprobe.d/nvidia.conf")
    if not udev_path.exists() or not modprobe_path.exists():
        return False
    try:
        modprobe_txt = modprobe_path.read_text()
        if "NVreg_DynamicPowerManagement=0x02" not in modprobe_txt:
            return False
        udev_txt = udev_path.read_text()
        if 'ATTR{power/control}="auto"' not in udev_txt:
            return False
        return True
    except OSError:
        return False


def fix_system_rules() -> List[Tuple[bool, str]]:
    """Install /etc/udev/rules.d/80-nvidia-pm.rules and /etc/modprobe.d/nvidia.conf using sudo."""
    results = []

    # Temporary files
    tmp_udev = Path("/tmp/80-nvidia-pm.rules")
    tmp_modprobe = Path("/tmp/nvidia-pm.conf")

    try:
        tmp_udev.write_text(UDEV_RULE_CONTENT)
        tmp_modprobe.write_text(MODPROBE_CONTENT)

        # Copy to system locations via sudo
        res_udev = subprocess.run(["sudo", "cp", str(tmp_udev), "/etc/udev/rules.d/80-nvidia-pm.rules"], capture_output=True, text=True)
        if res_udev.returncode == 0:
            results.append((True, "Installed /etc/udev/rules.d/80-nvidia-pm.rules"))
            subprocess.run(["sudo", "udevadm", "control", "--reload-rules"], check=False)
            subprocess.run(["sudo", "udevadm", "trigger"], check=False)
        else:
            results.append((False, f"Failed to copy udev rule: {res_udev.stderr}"))

        res_mod = subprocess.run(["sudo", "cp", str(tmp_modprobe), "/etc/modprobe.d/nvidia.conf"], capture_output=True, text=True)
        if res_mod.returncode == 0:
            results.append((True, "Installed /etc/modprobe.d/nvidia.conf"))
        else:
            results.append((False, f"Failed to copy modprobe config: {res_mod.stderr}"))

        # Cleanup
        tmp_udev.unlink(missing_ok=True)
        tmp_modprobe.unlink(missing_ok=True)
    except Exception as e:
        results.append((False, f"System rule error: {e}"))

    return results


def _normalize_pci_sysfs_path(path: Path | str) -> str:
    target_str = str(path)
    # If path is a resolved sysfs path like /sys/devices/pci0000:00/0000:00:01.0/power/control
    # Convert it to /sys/bus/pci/devices/0000:00:01.0/power/control so omalegion-write accepts it.
    m = re.search(r"(?:/sys/devices/pci[^/]+/)?(0000:[0-9a-fA-F]{2}:[0-9a-fA-F]{2}\.[0-9a-fA-F])/(power/[a-zA-Z0-9_]+|remove)$", target_str)
    if m:
        pci_addr = m.group(1)
        subpath = m.group(2)
        return f"/sys/bus/pci/devices/{pci_addr}/{subpath}"
    return target_str


def _write_sysfs(path: Path | str, value: str) -> bool:
    target_str = _normalize_pci_sysfs_path(path)
    target = Path(target_str)

    # If target already has this exact value, avoid waking device or calling sudo
    try:
        if target.exists() and target.read_text().strip() == value.strip():
            return True
    except OSError:
        pass

    if os.access(target, os.W_OK):
        try:
            target.write_text(f"{value}\n")
            return True
        except OSError:
            pass

    # Try omalegion-write via passwordless sudo
    if Path("/usr/local/bin/omalegion-write").exists():
        try:
            res = subprocess.run(
                ["sudo", "-n", "/usr/local/bin/omalegion-write", "write", target_str, value],
                capture_output=True,
                text=True,
                timeout=2.0,
            )
            if res.returncode == 0:
                return True
        except Exception:
            pass

    # Try pkexec or sudo tee
    for cmd in (
        ["pkexec", "bash", "-c", f"echo '{value}' > '{target_str}'"],
        ["sudo", "-n", "bash", "-c", f"echo '{value}' > '{target_str}'"],
    ):
        try:
            res = subprocess.run(cmd, capture_output=True, timeout=1.5)
            if res.returncode == 0:
                return True
        except Exception:
            pass
    return False


def apply_live_power_control() -> Tuple[bool, str]:
    """Ensure dGPU power/control and its parent bridge are 'auto' without waking up the card."""
    dgpu = find_nvidia_dgpu()
    if not dgpu:
        return False, "No NVIDIA dGPU found."

    control_file = Path(f"/sys/bus/pci/devices/{dgpu.pci_address}/power/control")
    try:
        if control_file.exists() and control_file.read_text().strip() != "auto":
            _write_sysfs(control_file, "auto")
    except OSError:
        pass

    parent_bridge_addr = dgpu.sysfs_path.resolve().parent.name
    parent_ctrl = Path(f"/sys/bus/pci/devices/{parent_bridge_addr}/power/control")
    try:
        if parent_ctrl.exists() and parent_ctrl.read_text().strip() != "auto":
            _write_sysfs(parent_ctrl, "auto")
    except OSError:
        pass

    return True, f"Set dGPU and parent bridge {parent_bridge_addr} to 'auto'."


def suspend_dgpu(force: bool = False) -> Tuple[bool, str, List[str]]:
    """Actively suspend the NVIDIA dGPU into D3cold (0.0 W).

    1. Checks if already in D3cold (avoiding unnecessary wake loops).
    2. Stops and disables nvidia-persistenced (which keeps driver awake).
    3. Disables driver persistence mode via nvidia-smi -pm 0.
    4. Detects and terminates rogue processes holding /dev/nvidia* if force is True.
    5. Removes or unbinds NVIDIA audio controller (0000:xx:00.1).
    6. Ensures power/control is 'auto' for both dGPU and parent PCIe root port.
    7. Polls runtime_status until suspended in D3cold or timeout.
    """
    from .pci import find_nvidia_audio, get_nvidia_client_processes, _read_trimmed

    logs: List[str] = []
    dgpu = find_nvidia_dgpu()
    if not dgpu:
        return False, "No NVIDIA dGPU found on PCI bus.", logs

    # Check if ALREADY suspended in D3cold (do NOT exit early if stuck in D3hot!)
    cur_status = _read_trimmed(dgpu.sysfs_path / "power" / "runtime_status")
    cur_state = _read_trimmed(dgpu.sysfs_path / "power_state")
    if cur_status == "suspended" and cur_state == "D3cold":
        logs.append(f"dGPU is already in {cur_state} ({cur_status}).")
        return True, f"dGPU is in deep sleep {cur_state} (0.0 W).", logs

    # 1. Stop and disable nvidia-persistenced if running
    try:
        check = subprocess.run(["systemctl", "is-active", "nvidia-persistenced"], capture_output=True, text=True, timeout=1.5)
        if check.stdout.strip() == "active":
            logs.append("Stopping nvidia-persistenced.service...")
            subprocess.run(["pkexec", "systemctl", "stop", "nvidia-persistenced"], capture_output=True, timeout=2.0)
            subprocess.run(["pkexec", "systemctl", "disable", "nvidia-persistenced"], capture_output=True, timeout=2.0)
            logs.append("nvidia-persistenced stopped and disabled.")
    except Exception as e:
        logs.append(f"Warning: Failed to check/stop nvidia-persistenced: {e}")

    # 2. Disable persistence mode via nvidia-smi
    try:
        subprocess.run(["nvidia-smi", "-pm", "0"], capture_output=True, timeout=2.0)
        logs.append("Persistence mode set to Off (nvidia-smi -pm 0).")
    except Exception:
        pass

    # 3. Check for client processes holding the GPU
    clients = get_nvidia_client_processes()
    if clients:
        pids = [c["pid"] for c in clients]
        names = [f"{c['comm']} (PID {c['pid']})" for c in clients]
        logs.append(f"Found active GPU clients: {', '.join(names)}")
        if force:
            logs.append("Terminating client processes holding dGPU...")
            for pid in pids:
                try:
                    os.kill(pid, 15)  # SIGTERM
                except OSError:
                    pass
            import time
            time.sleep(0.5)
            for pid in pids:
                try:
                    os.kill(pid, 9)  # SIGKILL
                except OSError:
                    pass
        else:
            logs.append("Note: Pass --force to terminate rogue processes holding the dGPU.")

    # 4. Remove audio function if present
    audio = find_nvidia_audio()
    if audio and audio.exists():
        remove_file = audio / "remove"
        if remove_file.exists():
            _write_sysfs(remove_file, "1")
            logs.append(f"Removed audio controller {audio.name} from PCI bus.")

    # 5. Set power/control to auto for dGPU
    ctrl_file = Path(f"/sys/bus/pci/devices/{dgpu.pci_address}/power/control")
    if ctrl_file.exists():
        try:
            if ctrl_file.read_text().strip() == "auto":
                logs.append(f"{ctrl_file} already 'auto'.")
            elif _write_sysfs(ctrl_file, "auto"):
                logs.append(f"Set {ctrl_file} -> auto.")
            else:
                logs.append(f"Warning: Failed to set {ctrl_file} -> auto.")
        except Exception:
            _write_sysfs(ctrl_file, "auto")

    # Enforce parent bridge to 'auto' so the upstream PCIe root port powers down to L2/L3 (enabling D3cold)
    parent_bridge_addr = dgpu.sysfs_path.resolve().parent.name
    parent_ctrl = Path(f"/sys/bus/pci/devices/{parent_bridge_addr}/power/control")
    if parent_ctrl.exists():
        try:
            if parent_ctrl.read_text().strip() == "auto":
                logs.append(f"Parent bridge {parent_bridge_addr} already 'auto'.")
            elif _write_sysfs(parent_ctrl, "auto"):
                logs.append(f"Set parent bridge {parent_bridge_addr} -> auto (enabling D3cold).")
            else:
                logs.append(f"Warning: Failed to set parent bridge {parent_bridge_addr} -> auto.")
        except Exception:
            _write_sysfs(parent_ctrl, "auto")

    # 6. Active verification polling loop (up to 7s to cover 5s autosuspend delay)
    import time
    for _ in range(28):  # 28 * 0.25s = 7.0s
        time.sleep(0.25)
        status = _read_trimmed(dgpu.sysfs_path / "power" / "runtime_status")
        state = _read_trimmed(dgpu.sysfs_path / "power_state")
        if status == "suspended" and state == "D3cold":
            return True, f"dGPU successfully suspended to D3cold (status={status}, state={state}, 0.0 W).", logs

    status = _read_trimmed(dgpu.sysfs_path / "power" / "runtime_status")
    state = _read_trimmed(dgpu.sysfs_path / "power_state")

    # Check kernel logs for GSP firmware wedge
    try:
        dmesg_check = subprocess.run(["dmesg", "--since", "5 minutes ago"], capture_output=True, text=True, timeout=1.0)
        if "NV_ERR_RESET_REQUIRED" in dmesg_check.stdout or "Error while waiting for GPU progress" in dmesg_check.stdout:
            logs.append("Kernel warning: NVIDIA GSP firmware is wedged (NV_ERR_RESET_REQUIRED). A reboot is required to reset the GPU processor.")
    except Exception:
        pass

    return False, f"dGPU remains {status} ({state}).", logs
