"""Auto-remediation engine for NVIDIA hybrid laptop power issues.

Implements safe, atomic configuration updates for udev, modprobe, compositor env,
btop, and on-demand prime-run script.
"""

from __future__ import annotations

import os
import re
import subprocess
from pathlib import Path
from typing import List, Tuple

from .pci import find_nvidia_dgpu

UDEV_RULE_CONTENT = """# Automatically generated by dgpu-doctor

# Remove NVIDIA USB xHCI Host Controller devices, if present
ACTION=="add", SUBSYSTEM=="pci", ATTR{vendor}=="0x10de", ATTR{class}=="0x0c0330", ATTR{remove}="1"

# Remove NVIDIA USB Type-C UCSI devices, if present
ACTION=="add", SUBSYSTEM=="pci", ATTR{vendor}=="0x10de", ATTR{class}=="0x0c8000", ATTR{remove}="1"

# Remove NVIDIA Audio devices on boot so WirePlumber cannot block D3cold
ACTION=="add", SUBSYSTEM=="pci", ATTR{vendor}=="0x10de", ATTR{class}=="0x040300", ATTR{remove}="1"

# Enable runtime PM for NVIDIA VGA/3D controller devices on driver bind
ACTION=="bind", SUBSYSTEM=="pci", ATTR{vendor}=="0x10de", ATTR{class}=="0x030000", TEST=="power/control", ATTR{power/control}="auto"
ACTION=="bind", SUBSYSTEM=="pci", ATTR{vendor}=="0x10de", ATTR{class}=="0x030200", TEST=="power/control", ATTR{power/control}="auto"

# Disable runtime PM for NVIDIA VGA/3D controller devices on driver unbind
ACTION=="unbind", SUBSYSTEM=="pci", ATTR{vendor}=="0x10de", ATTR{class}=="0x030000", TEST=="power/control", ATTR{power/control}="on"
ACTION=="unbind", SUBSYSTEM=="pci", ATTR{vendor}=="0x10de", ATTR{class}=="0x030200", TEST=="power/control", ATTR{power/control}="on"
"""

MODPROBE_CONTENT = """# Automatically generated by dgpu-doctor

options nvidia-drm modeset=1
options nvidia "NVreg_DynamicPowerManagement=0x02"
options nvidia NVreg_UsePageAttributeTable=1 NVreg_InitializeSystemMemoryAllocations=0
"""

PRIME_RUN_CONTENT = """#!/usr/bin/env bash
# On-demand NVIDIA Prime Offload wrapper
# Automatically wakes the dGPU, runs the game, and allows it to sleep on exit.

export __NV_PRIME_RENDER_OFFLOAD=1
export __VK_LAYER_NV_optimus=NVIDIA_only
export __GLX_VENDOR_LIBRARY_NAME=nvidia
unset __EGL_VENDOR_LIBRARY_FILENAMES

exec "$@"
"""


def fix_btop() -> Tuple[bool, str]:
    """Reconfigure ~/.config/btop/btop.conf to isolate monitoring to iGPU."""
    conf = Path.home() / ".config/btop/btop.conf"
    if not conf.exists():
        return False, "btop.conf does not exist (btop not installed or not run yet)."

    try:
        text = conf.read_text()
        modified = text

        # Turn off GPU in CPU box if set to Auto
        modified = re.sub(r'show_gpu_info\s*=\s*"Auto"', 'show_gpu_info = "Off"', modified)
        # Disable NVML PCIe speeds
        modified = re.sub(
            r"nvml_measure_pcie_speeds\s*=\s*true", "nvml_measure_pcie_speeds = false", modified
        )
        # Isolate shown GPUs to intel
        modified = re.sub(r'shown_gpus\s*=\s*"[^"]*"', 'shown_gpus = "intel"', modified)

        if modified != text:
            conf.write_text(modified)
            return True, "Optimized ~/.config/btop/btop.conf to monitor iGPU only."
        return True, "btop.conf is already optimized."
    except Exception as e:
        return False, f"Failed to modify btop.conf: {e}"


def fix_compositor_env() -> List[Tuple[bool, str]]:
    """Configure environment files so Wayland compositors don't leak NVIDIA EGL fds."""
    results = []
    mesa_val = "__EGL_VENDOR_LIBRARY_FILENAMES=/usr/share/glvnd/egl_vendor.d/50_mesa.json"
    intel_val = "AQ_DRM_DEVICES=/dev/dri/card2"

    # 1. ~/.config/environment.d/10-hyprland-gpu.conf
    env_dir = Path.home() / ".config/environment.d"
    env_file = env_dir / "10-hyprland-gpu.conf"
    try:
        env_dir.mkdir(parents=True, exist_ok=True)
        content = f"{intel_val}\n{mesa_val}\n"
        env_file.write_text(content)
        results.append((True, f"Updated {env_file}"))
    except Exception as e:
        results.append((False, f"Failed to write {env_file}: {e}"))

    # 2. ~/.config/uwsm/env-hyprland
    uwsm_dir = Path.home() / ".config/uwsm"
    uwsm_file = uwsm_dir / "env-hyprland"
    try:
        uwsm_dir.mkdir(parents=True, exist_ok=True)
        lines = []
        if uwsm_file.exists():
            lines = [l for l in uwsm_file.read_text().splitlines() if not l.startswith("export AQ_DRM_DEVICES") and not l.startswith("export __EGL_VENDOR_LIBRARY_FILENAMES")]
        lines.append(f"export {intel_val}")
        lines.append(f"export {mesa_val}")
        uwsm_file.write_text("\n".join(lines) + "\n")
        results.append((True, f"Updated {uwsm_file}"))
    except Exception as e:
        results.append((False, f"Failed to write {uwsm_file}: {e}"))

    return results


def install_prime_run() -> Tuple[bool, str]:
    """Install ~/.local/bin/prime-run."""
    bin_dir = Path.home() / ".local/bin"
    bin_file = bin_dir / "prime-run"
    try:
        bin_dir.mkdir(parents=True, exist_ok=True)
        bin_file.write_text(PRIME_RUN_CONTENT)
        bin_file.chmod(0o755)
        return True, f"Installed on-demand runner: {bin_file}"
    except Exception as e:
        return False, f"Failed to install prime-run: {e}"


def fix_system_rules() -> List[Tuple[bool, str]]:
    """Install /etc/udev/rules.d/80-nvidia-pm.rules and /etc/modprobe.d/nvidia.conf using sudo."""
    results = []

    # Temporary files
    tmp_udev = Path("/tmp/80-nvidia-pm.rules")
    tmp_modprobe = Path("/tmp/nvidia-pm.conf")

    try:
        tmp_udev.write_text(UDEV_RULE_CONTENT)
        tmp_modprobe.write_text(MODPROBE_CONTENT)

        # Copy to system locations via sudo
        res_udev = subprocess.run(["sudo", "cp", str(tmp_udev), "/etc/udev/rules.d/80-nvidia-pm.rules"], capture_output=True, text=True)
        if res_udev.returncode == 0:
            results.append((True, "Installed /etc/udev/rules.d/80-nvidia-pm.rules"))
            subprocess.run(["sudo", "udevadm", "control", "--reload-rules"], check=False)
            subprocess.run(["sudo", "udevadm", "trigger"], check=False)
        else:
            results.append((False, f"Failed to copy udev rule: {res_udev.stderr}"))

        res_mod = subprocess.run(["sudo", "cp", str(tmp_modprobe), "/etc/modprobe.d/nvidia.conf"], capture_output=True, text=True)
        if res_mod.returncode == 0:
            results.append((True, "Installed /etc/modprobe.d/nvidia.conf"))
        else:
            results.append((False, f"Failed to copy modprobe config: {res_mod.stderr}"))

        # Cleanup
        tmp_udev.unlink(missing_ok=True)
        tmp_modprobe.unlink(missing_ok=True)
    except Exception as e:
        results.append((False, f"System rule error: {e}"))

    return results


def apply_live_power_control() -> Tuple[bool, str]:
    """Ensure dGPU power/control is 'auto' and kick device into suspend if wedged."""
    dgpu = find_nvidia_dgpu()
    if not dgpu:
        return False, "No NVIDIA dGPU found."

    control_file = dgpu.sysfs_path / "power" / "control"
    try:
        def _write_val(val: str) -> bool:
            if os.access(control_file, os.W_OK):
                control_file.write_text(f"{val}\n")
                return True
            try:
                res = subprocess.run(["sudo", "-n", "tee", str(control_file)], input=f"{val}\n", text=True, capture_output=True, timeout=2.0)
                if res.returncode == 0:
                    return True
            except Exception:
                pass
            if Path("/usr/local/bin/omalegion-write").exists():
                try:
                    res2 = subprocess.run(["sudo", "-n", "/usr/local/bin/omalegion-write", "write", str(control_file), val], capture_output=True, text=True, timeout=2.0)
                    return res2.returncode == 0
                except Exception:
                    pass
            return False

        current_ctrl = control_file.read_text().strip() if control_file.exists() else ""
        current_status = dgpu.runtime_status

        # If control is already auto but GPU is stuck active with no clients, cycle on -> auto
        if current_ctrl == "auto" and current_status == "active":
            _write_val("on")
            import time
            time.sleep(0.2)
            if _write_val("auto"):
                return True, f"Cycled {control_file} (on -> auto) to clear wedged state."

        if _write_val("auto"):
            return True, f"Set {control_file} to 'auto'."

        return False, f"Need root permissions to write to {control_file}."
    except Exception as e:
        return False, f"Error writing power control: {e}"
