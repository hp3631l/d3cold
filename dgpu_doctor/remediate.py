def fix_btop() -> Tuple[bool, str]:
    conf = Path.home() / ".config/btop/btop.conf"
    if not conf.exists():
        return False, "btop.conf does not exist."
    try:
        text = conf.read_text()
        mod = re.sub(r'show_gpu_info\s*=\s*"Auto"', 'show_gpu_info = "Off"', text)
        mod = re.sub(r"nvml_measure_pcie_speeds\s*=\s*true", "nvml_measure_pcie_speeds = false", mod)
        mod = re.sub(r'shown_gpus\s*=\s*"[^"]*"', 'shown_gpus = "intel"', mod)
        if mod != text:
            conf.write_text(mod)
            return True, "Optimized ~/.config/btop/btop.conf to monitor iGPU only."
        return True, "btop.conf is already optimized."
    except Exception as e:
        return False, f"Failed to modify btop.conf: {e}"


def fix_compositor_env() -> List[Tuple[bool, str]]:
    from .pci import find_dgpu_drm_card, find_igpu_drm_card
    results = []
    igpu, dgpu = find_igpu_drm_card(), find_dgpu_drm_card()
    intel_val = f"AQ_DRM_DEVICES={igpu}:{dgpu}" if dgpu else f"AQ_DRM_DEVICES={igpu}"

    # 1. ~/.config/environment.d/10-hyprland-gpu.conf
    env_file = Path.home() / ".config/environment.d/10-hyprland-gpu.conf"
    try:
        env_file.parent.mkdir(parents=True, exist_ok=True)
        env_file.write_text(f"{intel_val}\n")
        results.append((True, f"Updated {env_file} (AQ_DRM_DEVICES pinned to iGPU)"))
    except Exception as e:
        results.append((False, f"Failed to write {env_file}: {e}"))

    # 2. Clean uwsm configs
    for name in ("env-hyprland", "env"):
        ufile = Path.home() / f".config/uwsm/{name}"
        if ufile.parent.exists():
            try:
                prefixes = ("export AQ_DRM_DEVICES", "export __EGL_VENDOR_LIBRARY_FILENAMES", "export VK_DRIVER_FILES", "export LIBVA_DRIVER_NAME")
                lines = [l for l in ufile.read_text().splitlines() if not any(l.startswith(p) for p in prefixes)] if ufile.exists() else []
                lines.append(f"export {intel_val}")
                ufile.write_text("\n".join(lines) + "\n")
                results.append((True, f"Updated {ufile} (purged global driver locks)"))
            except Exception as e:
                results.append((False, f"Failed to write {ufile}: {e}"))

    # 3. Clean hyprland.lua
    hlua = Path.home() / ".config/hypr/hyprland.lua"
    if hlua.exists():
        try:
            txt = hlua.read_text()
            mod = re.sub(r'hl\.env\("(__EGL_VENDOR_LIBRARY_FILENAMES|VK_DRIVER_FILES|LIBVA_DRIVER_NAME)",\s*"[^"]*"\)\n?', '', txt)
            if mod != txt:
                hlua.write_text(mod)
                results.append((True, "Purged global driver locks from ~/.config/hypr/hyprland.lua"))
                subprocess.run(["hyprctl", "reload"], check=False, capture_output=True)
        except Exception as e:
            results.append((False, f"Failed to clean hyprland.lua: {e}"))

    # 4. Clean systemd user session
    try:
        subprocess.run(["systemctl", "--user", "unset-environment", "VK_DRIVER_FILES", "__EGL_VENDOR_LIBRARY_FILENAMES", "LIBVA_DRIVER_NAME"], check=False, capture_output=True)
        subprocess.run(["systemctl", "--user", "daemon-reload"], check=False, capture_output=True)
        results.append((True, "Cleared session environment locks in systemd --user"))
    except Exception as e:
        results.append((False, f"Failed to unset systemd environment: {e}"))
    return results


def install_prime_run() -> Tuple[bool, str]:
    bin_file = Path.home() / ".local/bin/prime-run"
    try:
        bin_file.parent.mkdir(parents=True, exist_ok=True)
        bin_file.write_text(PRIME_RUN_CONTENT)
        bin_file.chmod(0o755)
        return True, f"Installed on-demand runner: {bin_file}"
    except Exception as e:
        return False, f"Failed to install prime-run: {e}"


def are_system_rules_installed() -> bool:
    has_udev = any(Path(p).exists() and "0x10de" in Path(p).read_text() for p in ("/etc/udev/rules.d/80-nvidia-pm.rules", "/etc/udev/rules.d/99-nvidia-pm.rules"))
    has_modprobe = any(Path(p).exists() and "NVreg_DynamicPowerManagement=0x02" in Path(p).read_text() for p in ("/etc/modprobe.d/nvidia-pm.conf", "/etc/modprobe.d/nvidia.conf"))
    return has_udev and has_modprobe


def fix_system_rules() -> List[Tuple[bool, str]]:
    results = []
    sudo = ["sudo", "-n"] if subprocess.run(["sudo", "-n", "true"], capture_output=True).returncode == 0 else (["pkexec"] if os.environ.get("DISPLAY") or os.environ.get("WAYLAND_DISPLAY") else ["sudo"])
    try:
        subprocess.run(sudo + ["tee", "/etc/udev/rules.d/80-nvidia-pm.rules"], input=UDEV_RULE_CONTENT, text=True, check=True, capture_output=True)
        subprocess.run(sudo + ["udevadm", "control", "--reload-rules"], check=True, capture_output=True)
        subprocess.run(sudo + ["udevadm", "trigger"], check=True, capture_output=True)
        results.append((True, "Installed /etc/udev/rules.d/80-nvidia-pm.rules and reloaded udev"))
    except Exception as e:
        results.append((False, f"Failed to install udev rules: {e}"))
    try:
        subprocess.run(sudo + ["tee", "/etc/modprobe.d/nvidia-pm.conf"], input=MODPROBE_CONTENT, text=True, check=True, capture_output=True)
        results.append((True, "Installed /etc/modprobe.d/nvidia-pm.conf"))
    except Exception as e:
        results.append((False, f"Failed to install modprobe configuration: {e}"))
    return results


def _set_power_control_auto(path: Path) -> Tuple[bool, str]:
    if not path.exists():
        return True, "not present"
    dev_name = path.parent.name if path.parent.name != "power" else path.parent.parent.name
    try:
        if path.read_text().strip() == "auto":
            return True, f"{dev_name} is already 'auto'"
        path.write_text("auto")
        return True, f"Set {dev_name} to 'auto'"
    except PermissionError:
        sudo = ["sudo", "-n"] if subprocess.run(["sudo", "-n", "true"], capture_output=True).returncode == 0 else (["pkexec"] if os.environ.get("DISPLAY") or os.environ.get("WAYLAND_DISPLAY") else ["sudo"])
        res = subprocess.run(sudo + ["tee", str(path)], input="auto", text=True, capture_output=True)
        if res.returncode == 0:
            return True, f"Set {dev_name} to 'auto' (elevated)"
        return False, f"Failed {dev_name}: permission denied (requires sudo)"
    except OSError as e:
        return False, f"Failed {dev_name}: {e}"


def apply_live_power_control() -> Tuple[bool, str]:
    dgpu = find_nvidia_dgpu()
    if not dgpu:
        return False, "No NVIDIA dGPU found."
    from .pci import find_nvidia_audio
    targets = [dgpu.sysfs_path / "power" / "control"]
    audio = find_nvidia_audio()
    if audio:
        targets.append(audio / "power" / "control")
    try:
        targets.append(dgpu.sysfs_path.resolve().parent / "power" / "control")
    except Exception:
        pass

    results = [_set_power_control_auto(p) for p in targets]
    all_ok = all(ok for ok, _ in results)
    msgs = [msg for _, msg in results if msg != "not present"]
    return all_ok, "; ".join(msgs) if msgs else "No controls modified."


def kill_nvidia_clients(force: bool = False) -> List[Tuple[int, str, bool]]:
    from .pci import get_nvidia_client_processes
    results = []
    if not force:
        return results
    import signal
    for c in get_nvidia_client_processes():
        pid, comm = c["pid"], c["comm"]
        try:
            os.kill(pid, signal.SIGTERM)
            time.sleep(0.2)
            os.kill(pid, signal.SIGKILL)
            results.append((pid, comm, True))
        except ProcessLookupError:
            results.append((pid, comm, True))
        except OSError:
            results.append((pid, comm, False))
    return results


def suspend_dgpu(force: bool = False, max_wait_sec: float = 8.0) -> Tuple[bool, str, List[str]]:
    logs = []
    dgpu = find_nvidia_dgpu()
    if not dgpu:
        return False, "No discrete NVIDIA GPU detected.", logs
    if dgpu.is_suspended:
        logs.append(f"dGPU is already in {dgpu.power_state} ({dgpu.runtime_status}).")
        return True, f"dGPU is in deep sleep {dgpu.power_state} (0.0 W).", logs

    # Terminate clients if force
    if force:
        for pid, comm, ok in kill_nvidia_clients(force=True):
            logs.append(f"Terminated client: {comm} (PID {pid})")

    # Disable persistence mode
    subprocess.run(["nvidia-smi", "-pm", "0"], capture_output=True, check=False)
    logs.append("Persistence mode set to Off (nvidia-smi -pm 0).")

    # Ensure power/control is auto
    apply_live_power_control()

    # Poll for suspension
    start = time.time()
    while (time.time() - start) < max_wait_sec:
        if dgpu.is_suspended:
            logs.append(f"dGPU transitioned to {dgpu.power_state} ({dgpu.runtime_status}) in {time.time()-start:.1f}s.")
            return True, f"dGPU successfully entered {dgpu.power_state} sleep (0.0 W).", logs
        time.sleep(0.5)

    cur = dgpu.runtime_status
    if cur == "suspending":
        return True, "dGPU is actively entering sleep (suspending).", logs
    return False, f"dGPU remains active ({dgpu.power_state}/{cur}).", logs
